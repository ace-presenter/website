#!/usr/bin/env python3
"""gen-presenter-plans.py — the pricing page's "every feature" table, from the
ONE document the apps lock against: ACE-Presenter-Mac docs/V3_PLANS.md.

The apps' plan locks (ACEDomain/PlanLocks.swift, src/domain/PlanLocks.h) and
this page must say the same thing, so neither is typed by hand.

    python3 scripts/gen-presenter-plans.py ../ACE-Presenter-Mac-v3/docs/V3_PLANS.md

writes src/lib/presenterPlans.ts. The owner's planning remarks (the italic
notes) are dropped except plain plan limits ("Free: …", "Pro: …"); cloud-speech
minutes come from the limits table.
"""
import json, re, sys

src = open(sys.argv[1], encoding="utf-8").read()

# Functions not on Windows yet, named on the page rather than implied.
MAC_ONLY = {
    "Syphon output", "SDI output (Blackmagic)", "Record the program", "Sermon recording + chapter marks",
    "Past recordings, captions and transcript export", "AI sermon notes", "MIDI control",
    "Linked computers (backup Mac)", "Several stream destinations at once", "Apple speech (macOS 26)",
    "Stream health",
}
SECTIONS = [("free", "## Free"), ("pro", "## Pro"), ("venue", "## Venue only")]

def section(start):
    i = src.index(start)
    j = src.find("\n## ", i + 1)
    return src[i: j if j > 0 else len(src)]

out = {}
for key, head in SECTIONS:
    groups, cur = [], None
    for line in section(head).splitlines():
        m = re.match(r"^\*\*(.+)\*\*\s*$", line)
        if m:
            cur = {"group": m.group(1), "items": []}; groups.append(cur); continue
        m = re.match(r"^- (.+?)(?:\s+—\s+_(.+)_)?\s*$", line)
        if m and cur is not None:
            name, note = m.group(1).strip(), (m.group(2) or "").strip()
            keep = note if re.match(r"^(Free|Pro|Venue)\b[^.]*:", note) else ""
            if name.startswith("Cloud speech"): keep = "Pro: 300 minutes a month · Venue: 900"
            if name.startswith("Buy more cloud minutes"): keep = ""
            item = {"name": name}
            if keep: item["limit"] = keep.replace("_", "")
            if name in MAC_ONLY: item["macOnly"] = True
            cur["items"].append(item)
    out[key] = [g for g in groups if g["items"]]

# The limits table, as rows.
rows = []
for line in section("## Limits").splitlines():
    cells = [c.strip() for c in line.strip().strip("|").split("|")]
    if len(cells) == 4 and cells[0] not in ("Where", "---") and not set(cells[0]) <= set("-"):
        rows.append({"where": cells[0], "free": cells[1], "pro": cells[2], "venue": cells[3]})
for r in rows:
    for k in ("free", "pro", "venue"):
        r[k] = re.sub(r"\s*\(was [^)]*\)", "", r[k])
        r[k] = re.sub(r",? *price going up \(new Stripe catalogue\)", "", r[k])
        r[k] = r[k].replace("Packs", "Packs available")

ts = ("// GENERATED by scripts/gen-presenter-plans.py from ACE-Presenter-Mac docs/V3_PLANS.md\n"
      "// — the same plans the apps enforce. Do not edit by hand.\n\n"
      "export type PlanItem = { name: string; limit?: string; macOnly?: boolean };\n"
      "export type PlanGroup = { group: string; items: PlanItem[] };\n"
      "export type LimitRow = { where: string; free: string; pro: string; venue: string };\n\n"
      f"export const PRESENTER_LIMITS: LimitRow[] = {json.dumps(rows, ensure_ascii=False, indent=2)};\n\n"
      f"export const PRESENTER_FREE: PlanGroup[] = {json.dumps(out['free'], ensure_ascii=False, indent=2)};\n\n"
      f"export const PRESENTER_PRO: PlanGroup[] = {json.dumps(out['pro'], ensure_ascii=False, indent=2)};\n\n"
      f"export const PRESENTER_VENUE: PlanGroup[] = {json.dumps(out['venue'], ensure_ascii=False, indent=2)};\n")
open("src/lib/presenterPlans.ts", "w", encoding="utf-8").write(ts)
n = sum(len(g["items"]) for k in out for g in out[k])
print(f"wrote src/lib/presenterPlans.ts: {len(rows)} limits, {n} functions")

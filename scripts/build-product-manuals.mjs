// Generates src/app/<route>/manual/manual.generated.ts for each product manual
// under content/manuals/<key>/*.md. Discovery-based: chapters are whatever .md
// files exist, ordered README → NN-* → appendix-*; titles come from each file's
// H1. Committed output so Vercel needs no pandoc. Run: node scripts/build-product-manuals.mjs
import { execSync } from "child_process";
import { writeFileSync, readdirSync, readFileSync, existsSync, mkdirSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, resolve } from "path";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

const PRODUCTS = [
  { key: "schedule", route: "schedule" },
  { key: "editors-notes", route: "editors-notes" },
  { key: "manager", route: "manager" },
  { key: "world", route: "world" },
];

const anchor = (fn) => "sec-" + fn.replace(/\.md$/, "");
const h1of = (path) => {
  const m = readFileSync(path, "utf8").match(/^#\s+(.+?)\s*$/m);
  return m ? m[1].replace(/[*_`]/g, "").trim() : "";
};
function meta(fn, path) {
  const title = h1of(path) || fn.replace(/\.md$/, "");
  if (/^readme\.md$/i.test(fn)) return { order: -1, num: "", eyebrow: "Overview", title };
  const n = fn.match(/^(\d{1,2})[-.]/);
  if (n) return { order: parseInt(n[1], 10), num: String(parseInt(n[1], 10)), eyebrow: `Chapter ${parseInt(n[1], 10)}`, title };
  const a = fn.match(/^appendix[-_]?([a-z])/i);
  if (a) return { order: 1000 + a[1].toLowerCase().charCodeAt(0), num: a[1].toUpperCase(), eyebrow: `Appendix ${a[1].toUpperCase()}`, title };
  return { order: 500, num: "", eyebrow: title, title };
}

const badges = [
  ["(coming soon)", "soon", "coming soon"],
  ["(in development)", "dev", "in development"],
  ["(preview)", "preview", "preview"],
  ["(planned)", "planned", "planned"],
  ["(beta)", "beta", "beta"],
  ["(early access)", "early", "early access"],
  ["(Pro)", "pro", "Pro"],
  ["(macOS only)", "mac", "macOS only"],
  ["(Windows only)", "win", "Windows only"],
  ["(web)", "web", "web"],
];

for (const { key, route } of PRODUCTS) {
  const dir = resolve(root, "content/manuals", key);
  if (!existsSync(dir)) continue;
  const mds = readdirSync(dir).filter((f) => f.endsWith(".md"));
  if (mds.length === 0) {
    console.log(`skip ${key}: no .md yet`);
    continue;
  }
  const entries = mds
    .map((fn) => ({ fn, ...meta(fn, resolve(dir, fn)) }))
    .sort((a, b) => a.order - b.order);

  let html = "";
  const nav = [];
  for (const e of entries) {
    let frag = execSync(`pandoc --from gfm --to html5 "${resolve(dir, e.fn)}"`, { encoding: "utf8", maxBuffer: 1e7 });
    frag = frag.replace(/href="([0-9a-zA-Z-]+)\.md(#[^"]*)?"/g, (_m, base) => `href="#sec-${base}"`);
    if (/^readme\.md$/i.test(e.fn)) frag = frag.replace(/<h2[^>]*>(Table of contents|Contents)<\/h2>[\s\S]*?<\/ul>/i, "");
    frag = frag.replace(/<h1[^>]*>[\s\S]*?<\/h1>/i, ""); // divider/head carries the title
    const cue = `<div class="doc-cue"><span class="cue-rule" aria-hidden="true"></span><span class="cue-tag">${e.eyebrow}</span></div>`;
    html += `<section id="${anchor(e.fn)}" class="doc" data-num="${e.num}">\n${cue}\n${frag}\n</section>\n`;
    nav.push({ id: anchor(e.fn), title: e.title, num: e.num });
  }
  for (const [needle, cls, text] of badges) html = html.split(needle).join(`<span class="badge b-${cls}">${text}</span>`);

  const outDir = resolve(root, "src/app", route, "manual");
  mkdirSync(outDir, { recursive: true });
  const out = `// AUTO-GENERATED by scripts/build-product-manuals.mjs — do not edit by hand.
// Source: content/manuals/${key}/*.md
export type ManualNavItem = { id: string; title: string; num: string };
export const MANUAL_NAV: ManualNavItem[] = ${JSON.stringify(nav, null, 2)};
export const MANUAL_HTML: string = ${JSON.stringify(html)};
`;
  writeFileSync(resolve(outDir, "manual.generated.ts"), out);
  console.log(`wrote ${route}/manual/manual.generated.ts — ${nav.length} sections, ${html.length} chars`);
}
